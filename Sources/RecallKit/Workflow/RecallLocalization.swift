import Foundation

public enum AppLanguage: String, CaseIterable, Sendable {
    case system, english = "en", chinese = "zh-Hans"
    public var label: String { switch self { case .system: RecallLocalization.both("跟随系统", "System"); case .english: "English"; case .chinese: "简体中文" } }
}
/// Compiled strings keep the existing SwiftPM developer launch path self-contained.
/// Stable Chinese keys preserve current documents and stored state; no user content is rewritten.
public enum RecallLocalization {
    public static let languageKey = "recall.interface-language"
    public static let outputKey = "recall.output-language"
    public static var isEnglish: Bool {
        switch AppLanguage(rawValue: UserDefaults.standard.string(forKey: languageKey) ?? "system") ?? .system {
        case .english: true
        case .chinese: false
        case .system: !(Locale.preferredLanguages.first ?? "en").hasPrefix("zh")
        }
    }
    public static var outputCode: String {
        let choice = UserDefaults.standard.string(forKey: outputKey) ?? "system"
        return choice == "system" ? (isEnglish ? "en" : "zh-Hans") : choice
    }
    public static var locale: Locale {
        Locale(identifier: (isEnglish ? "en_" : "zh_Hans_") + (Locale.current.region?.identifier ?? "US"))
    }
    public static func text(_ source: String) -> String {
        guard isEnglish else { return source }
        if let translated = english[source] { return translated }
        #if DEBUG
        fputs("RecallLocalization missing translation: \(source)\n", stderr)
        #endif
        return source
    }
    /// Chinese interface strings passed to `text` that have no English entry.
    public static func missingEnglishKeys(_ sources: [String]) -> [String] {
        sources.filter { english[$0] == nil }.sorted()
    }
    public static func both(_ chinese: String, _ english: String) -> String { isEnglish ? english : chinese }
    public static func languageInstruction(for request: LLMRequest) -> String {
        if request.purpose == .chat {
            return "\nRespond in the language of the user's question, unless they request another language. Keep verbatim quotes unchanged."
        }
        return "\nOutput human-readable titles, details and overview in " + (outputCode == "en" ? "English" : "Simplified Chinese") + ". Never translate quotes, IDs, enum values or the JSON schema. Use complete concise titles, never truncate mid-sentence."
    }
